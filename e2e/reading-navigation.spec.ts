import { formatCourseName } from "../lib/course-name";
import { test, expect } from "@playwright/test";
import { readFile } from "node:fs/promises";
import { createExam } from "./exam-helpers";

test("routes, browser history, read progress and reading preferences", async ({ page, request }) => {
  await page.goto("/");
  const exam = await createExam(page, "Navigazione");
  await expect(page).toHaveURL(`/esami/${exam.id}`);
  const header = await page.locator(".course-header").boundingBox();
  const upload = await page.locator(".upload-banner").boundingBox();
  const analysis = await page.locator(".course-analysis").boundingBox();
  expect(upload!.y).toBeGreaterThan(header!.y);
  expect(Math.abs(upload!.width - analysis!.width)).toBeLessThan(2);
  await page.getByRole("button", { name: "Torna alla home" }).click();
  await page.getByRole("button", { name: `Impostazioni ${exam.name}`, exact: true }).click();
  const plan = page.getByRole("dialog");
  exam.name += " aggiornato";
  await plan.getByRole("textbox", { name: "Nome esame", exact: true }).fill(exam.name);
  await plan.getByRole("button", { name: "Arancione", exact: true }).click();
  await plan.getByRole("button", { name: "Salva impostazioni", exact: true }).click();
  await expect(plan).toHaveCount(0);
  const card = page.locator(".exam-overview-card").filter({ hasText: exam.name });
  await expect(card).toHaveAttribute("data-folder-color", "orange");
  await card.getByRole("button", { name: `Apri esame ${exam.name}`, exact: true }).click();
  await expect(page).toHaveURL(`/esami/${exam.id}`);
  const uploaded = page.waitForResponse(r => r.url().endsWith("/api/documents") && r.request().method() === "POST");
  await page.getByLabel("Carica PDF o immagini", { exact: true }).setInputFiles({ name: "Lettura.pdf", mimeType: "application/pdf", buffer: await readFile("public/esempio.pdf") });
  const doc = await (await uploaded).json();
  await page.getByRole("button", { name: `Apri ${doc.name.replace(/\.pdf$/i, "")}`, exact: true }).click();
  try {
    await expect(page).toHaveURL(`/esami/${exam.id}/documenti/${doc.id}`);
    await expect(page.locator(".slide-stage canvas")).toBeVisible();
    await page.getByRole("button", { name: "Mostra pannello inferiore" }).click();
    const read = page.getByRole("button", { name: "Da leggere", exact: true });
    await expect(read).toHaveAttribute("aria-pressed", "false");
    await expect(page.locator(".slide-stage canvas")).toHaveCSS("outline-style", "none");
    await page.evaluate(() => { (document.activeElement as HTMLElement)?.blur(); });
    await page.keyboard.press("Space");
    await expect(page.locator(".chat-slide-label")).toHaveText("Slide 2");
    await expect(page.locator(".slide-stage canvas")).toHaveCSS("outline-style", "none");
    await page.getByRole("button", { name: "Slide precedente", exact: true }).click();
    await page.evaluate(() => { (document.activeElement as HTMLElement)?.blur(); });
    await expect(page.getByRole("button", { name: "Letta", exact: true })).toHaveAttribute("aria-pressed", "true");
    await expect(page.locator(".slide-stage canvas")).toHaveCSS("outline-color", "rgb(182, 217, 191)");
    await expect(page.locator(".slide-stage canvas")).toHaveCSS("border-radius", "12px");
    await expect(page.locator(".slide-stage canvas")).toHaveCSS("outline-style", "solid");
    await expect(page.locator(".slide-stage canvas")).toHaveCSS("outline-width", "5px");
    await expect.poll(async () => (await (await request.get(`/api/documents/${doc.id}`)).json()).slides[1]?.read).toBe(true);
    await page.keyboard.press("Space");
    await expect(page.locator(".chat-slide-label")).toHaveText("Slide 1");
    await expect(page.locator(".slide-stage canvas")).toHaveCSS("outline-style", "none");
    await expect.poll(async () => (await (await request.get(`/api/documents/${doc.id}`)).json()).slides[1]?.read).toBe(false);
    await page.getByRole("button", { name: "Impostazioni della lettura", exact: true }).click();
    await page.getByRole("slider", { name: "Dimensione del testo" }).fill("20");
    await page.getByRole("textbox", { name: "Appunti della slide 1" }).fill("Lo spazio negli appunti non cambia la lettura.");
    await page.keyboard.press("Space");
    await page.keyboard.press("Escape");
    await page.goBack();
    await expect(page.locator(".selected-exam")).toContainText(formatCourseName(exam.name));
    await page.goForward();
    await expect(page.locator(".slide-stage canvas")).toBeVisible();
    await page.reload();
    await expect(page.locator(".slide-stage canvas")).toBeVisible();
    await page.getByRole("button", { name: "Impostazioni della lettura", exact: true }).click();
    await expect(page.getByRole("slider", { name: "Dimensione del testo" })).toHaveValue("20");
    await page.keyboard.press("Escape");
    await page.setViewportSize({ width: 390, height: 844 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({ path: "test-results/reading-mobile.png" });
  } finally { await request.delete(`/api/documents/${doc.id}`); await request.delete(`/api/folders/${exam.id}`); }
});
